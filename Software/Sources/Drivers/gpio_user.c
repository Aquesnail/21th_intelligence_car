
#include "config.h"

// 强制所有端口进入用户手动控制模式
void GPIO_User_Control_On(void) {
    P0BP = 0xFF; P1BP = 0xFF; P2BP = 0xFF; P3BP = 0xFF;
    P4BP = 0xFF; P5BP = 0xFF; P6BP = 0xFF; P7BP = 0xFF;
    P8BP = 0xFF; P9BP = 0xFF; PABP = 0xFF; PBBP = 0xFF;
}

void GPIO_Init(void) {
    GPIO_User_Control_On();

    // ============================================================
    // --- P0口配置 ---
    // P0.0: RX          — 开漏, 弱上拉
    // P0.1: TX          — 推挽, 高速高驱
    // P0.2-P0.7: 其余   — 高阻输入
    // ============================================================
    P0M1 = (PIN_0 | PIN_2 | PIN_3 | PIN_4 | PIN_5 | PIN_6 | PIN_7);
    P0M0 = (PIN_0 | PIN_1);
    P0PU = PIN_0;                       // P0.0 弱上拉
    P0SR = ~PIN_1;                      // P0.1 高速摆率
    P0DR = PIN_1;                       // P0.1 增强驱动
    P0IE = 0xFF;
    P0NCS = 0x00;

    // ============================================================
    // --- P1口配置 ---
    // P1.0: ELECT_OUT_3 — 高阻输入
    // P1.4: ELECT_OUT_4 — 高阻输入
    // P1.5: ELECT_OUT_1 — 高阻输入
    // P1.6: ELECT_OUT_2 — 高阻输入
    // P1.1-P1.3, P1.7: 其余 — 高阻输入
    // ============================================================
    P1M1 = 0xFF;
    P1M0 = 0x00;
    P1PU = 0x00;
    P1IE  = 0xFF;
    P1INTE = 0x00;

    // ============================================================
    // --- P2口配置 ---
    // 全部高阻输入
    // ============================================================
    P2M1 = 0xFF;
    P2M0 = 0x00;
    P2PU = 0x00;
    P2IE  = 0xFF;
    P2INTE = 0x00;

    // ============================================================
    // --- P3口配置 ---
    // P3.3: SPI_IMU_INT2    — 开漏, 弱上拉
    // P3.4: SPI_IMU_INT1    — 开漏, 弱上拉
    // P3.6: SPI_MOTOR_INT2  — 开漏, 弱上拉
    // P3.7: SPI_MOTOR_INT1  — 开漏, 弱上拉
    // 其余: 高阻输入
    // ============================================================
    P3M1 = 0xFF;
    P3M0 = (PIN_3 | PIN_4 | PIN_6 | PIN_7);
    P3PU = (PIN_3 | PIN_4 | PIN_6 | PIN_7); // INT 引脚弱上拉
    P3IE  = 0xFF;
    P3INTE = 0x00;

    // ============================================================
    // --- P4口配置 ---
    // 全部高阻输入
    // ============================================================
    P4M1 = 0xFF;
    P4M0 = 0x00;
    P4PU = 0x00;
    P4IE  = 0xFF;
    P4INTE = 0x00;

    // ============================================================
    // --- P5口配置 ---
    // P5.0: PWM_LED_WS2812 — 推挽, 高速高驱
    // P5.4: KEY               — 开漏, 弱上拉, 下降沿中断
    // 其余: 高阻输入
    // ============================================================
    P5M1 = ~PIN_0;
    P5M0 = (PIN_0 | PIN_4);
    P5PU = PIN_4;                       // P5.4 弱上拉
    P5SR = ~PIN_0;                      // P5.0 高速摆率 (WS2812需要精确时序)
    P5DR = PIN_0;                       // P5.0 增强驱动
    P5IE  = 0xFF;
    P5IM2 &= ~PIN_4;                    // P5.4 中断模式: IM2=0
    P5IM1 &= ~PIN_4;                    //               IM1=0  → 下降沿触发
    P5IM0 &= ~PIN_4;                    //               IM0=0
    P5INTE = PIN_4;                     // P5.4 外部中断使能

    // ============================================================
    // --- P6口配置 ---
    // P6.4: SPI_IMU_CS   — 推挽, 弱上拉
    // P6.5: SPI_IMU_MOSI — 推挽, 高速高驱
    // P6.6: SPI_IMU_MISO — 开漏, 弱上拉
    // P6.7: SPI_IMU_CLK  — 推挽, 高速高驱
    // 其余: 高阻输入
    // ============================================================
    P6M1 = (PIN_0 | PIN_1 | PIN_2 | PIN_3 | PIN_6);
    P6M0 = (PIN_4 | PIN_5 | PIN_6 | PIN_7);
    P6PU = (PIN_4 | PIN_6);             // CS, MISO 弱上拉
    P6SR = ~(PIN_5 | PIN_7);            // MOSI, CLK 高速摆率
    P6DR = (PIN_5 | PIN_7);             // MOSI, CLK 增强驱动
    P6IE  = 0xFF;
    P6INTE = 0x00;

    // ============================================================
    // --- P7口配置 ---
    // P7.0: SPI_MOTOR_CS   — 推挽
    // P7.1: SPI_MOTOR_MOSI — 推挽, 高速高驱
    // P7.2: SPI_MOTOR_MISO — 开漏, 弱上拉
    // P7.3: SPI_MOTOR_CLK  — 推挽, 高速高驱
    // 其余: 高阻输入
    // ============================================================
    P7M1 = (PIN_2 | PIN_4 | PIN_5 | PIN_6 | PIN_7);
    P7M0 = (PIN_0 | PIN_1 | PIN_2 | PIN_3);
    P7PU = PIN_2;                       // MISO 弱上拉
    P7SR = ~(PIN_1 | PIN_3);            // MOSI, CLK 高速摆率
    P7DR = (PIN_1 | PIN_3);             // MOSI, CLK 增强驱动
    P7IE  = 0xFF;
    P7INTE = 0x00;

    // ============================================================
    // --- P8, P9, PA, PB口配置 ---
    // 全部高阻输入
    // ============================================================
    P8M1 = 0xFF; P8M0 = 0x00;
    P9M1 = 0xFF; P9M0 = 0x00;
    PAM1 = 0xFF; PAM0 = 0x00;
    PBM1 = 0xFF; PBM0 = 0x00;

    // --- 中断优先级全局配置 (全部最低级00) ---
    PINIPL  = 0x00; PINIPH  = 0x00;     // P0-P7中断优先级
    PIN2IPL = 0x00; PIN2IPH = 0x00;     // P8-PB中断优先级
}
